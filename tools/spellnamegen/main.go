// Command spellnamegen writes internal/spells/names.tsv.gz from the core's
// sql/base/tw_world_spell_template.sql: one "id<TAB>name" line per spell, in id order.
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"errors"
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	in := flag.String("in", "", "tw_world_spell_template.sql")
	out := flag.String("out", "", "names.tsv.gz to write")
	flag.Parse()
	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "usage: spellnamegen -in tw_world_spell_template.sql -out names.tsv.gz")
		os.Exit(2)
	}
	src, err := os.ReadFile(*in)
	if err == nil {
		var b []byte
		if b, err = Generate(src); err == nil {
			err = os.WriteFile(*out, b, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "spellnamegen:", err)
		os.Exit(1)
	}
}

var insert = regexp.MustCompile("INSERT INTO `spell_template` \\(([^)]*)\\) VALUES")

// Generate reads every INSERT INTO spell_template of the dump and returns the gzipped
// table. Each INSERT names its columns, so the entry and name columns are looked up per
// statement.
func Generate(src []byte) ([]byte, error) {
	names := map[uint64]string{}
	locs := insert.FindAllSubmatchIndex(src, -1)
	if len(locs) == 0 {
		return nil, errors.New("no INSERT INTO `spell_template`")
	}
	for _, loc := range locs {
		cols := strings.Split(strings.ReplaceAll(string(src[loc[2]:loc[3]]), "`", ""), ",")
		entry, name := -1, -1
		for i, c := range cols {
			switch strings.TrimSpace(c) {
			case "entry":
				entry = i
			case "name":
				name = i
			}
		}
		if entry < 0 || name < 0 {
			return nil, errors.New("an INSERT without entry or name")
		}
		rows, err := tuples(src[loc[1]:])
		if err != nil {
			return nil, err
		}
		for _, r := range rows {
			if len(r) != len(cols) {
				return nil, fmt.Errorf("a row of %d values for %d columns", len(r), len(cols))
			}
			id, err := strconv.ParseUint(r[entry], 10, 32)
			if err != nil {
				return nil, fmt.Errorf("entry %q: %w", r[entry], err)
			}
			if n := strings.TrimSpace(r[name]); n != "" {
				names[id] = strings.NewReplacer("\t", " ", "\n", " ", "\r", " ").Replace(n)
			}
		}
	}
	ids := make([]uint64, 0, len(names))
	for id := range names {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	var tsv bytes.Buffer
	fmt.Fprintf(&tsv, "# generated by tools/spellnamegen from tw_world_spell_template.sql (sha256 %x); DO NOT EDIT\n", sha256.Sum256(src))
	for _, id := range ids {
		fmt.Fprintf(&tsv, "%d\t%s\n", id, names[id])
	}
	var gz bytes.Buffer
	w, _ := gzip.NewWriterLevel(&gz, gzip.BestCompression)
	w.Write(tsv.Bytes())
	if err := w.Close(); err != nil {
		return nil, err
	}
	return gz.Bytes(), nil
}

// tuples reads "(v, 'text', ...), (...);" up to the semicolon that ends the statement:
// numbers, NULL and single-quoted strings with MySQL backslash escapes.
func tuples(b []byte) ([][]string, error) {
	var rows [][]string
	var row []string
	var cur strings.Builder
	inRow, inStr, have := false, false, false
	for i := 0; i < len(b); i++ {
		c := b[i]
		switch {
		case inStr:
			switch c {
			case '\\':
				if i+1 < len(b) {
					i++
					cur.WriteByte(unescape(b[i]))
				}
			case '\'':
				if i+1 < len(b) && b[i+1] == '\'' {
					cur.WriteByte('\'')
					i++
				} else {
					inStr = false
				}
			default:
				cur.WriteByte(c)
			}
		case c == '\'':
			inStr, have = true, true
		case c == '(' && !inRow:
			inRow, row = true, nil
		case c == ',' && inRow:
			row = append(row, value(cur.String(), have))
			cur.Reset()
			have = false
		case c == ')' && inRow:
			row = append(row, value(cur.String(), have))
			cur.Reset()
			have, inRow = false, false
			rows = append(rows, row)
		case c == ';' && !inRow:
			return rows, nil
		case inRow && c != ' ' && c != '\n' && c != '\r' && c != '\t':
			cur.WriteByte(c)
			have = true
		}
	}
	return nil, errors.New("statement not ended by ;")
}

// unescape is the character a MySQL backslash escape stands for.
func unescape(c byte) byte {
	switch c {
	case 'n':
		return '\n'
	case 't':
		return '\t'
	case 'r':
		return '\r'
	case '0':
		return 0
	}
	return c
}

func value(s string, have bool) string {
	if !have || s == "NULL" {
		return ""
	}
	return s
}
