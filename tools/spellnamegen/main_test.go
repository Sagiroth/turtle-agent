package main

import (
	"bytes"
	"compress/gzip"
	"io"
	"strings"
	"testing"
)

const sample = "DROP TABLE IF EXISTS `spell_template`;\n" +
	"INSERT INTO `spell_template` (`entry`, `school`, `name`, `nameSubtext`) VALUES\n" +
	"(430, 0, 'Drink', ''),\n(77, 0, 'Turtle\\'s Shell', NULL),\n(5, 1, 'Two''Quotes, (and parens);', 'x');\n" +
	"INSERT INTO `spell_template` (`name`, `entry`) VALUES ('Tab\\there', 9), ('', 10);\n"

func TestGenerate(t *testing.T) {
	out, err := Generate([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	zr, err := gzip.NewReader(bytes.NewReader(out))
	if err != nil {
		t.Fatal(err)
	}
	b, _ := io.ReadAll(zr)
	lines := strings.Split(strings.TrimSpace(string(b)), "\n")
	want := []string{"5\tTwo'Quotes, (and parens);", "9\tTab here", "77\tTurtle's Shell", "430\tDrink"}
	if len(lines) != 5 || !strings.HasPrefix(lines[0], "# generated by tools/spellnamegen") || strings.Join(lines[1:], "|") != strings.Join(want, "|") {
		t.Fatalf("%q", lines)
	}
}

func TestGenerateRejectsBadInput(t *testing.T) {
	for _, in := range []string{
		"nothing here",
		"INSERT INTO `spell_template` (`entry`, `school`) VALUES (1, 2);",
		"INSERT INTO `spell_template` (`entry`, `name`) VALUES (1, 'a', 3);",
		"INSERT INTO `spell_template` (`entry`, `name`) VALUES (x, 'a');",
		"INSERT INTO `spell_template` (`entry`, `name`) VALUES (1, 'a')",
	} {
		if _, err := Generate([]byte(in)); err == nil {
			t.Errorf("accepted %q", in)
		}
	}
}
