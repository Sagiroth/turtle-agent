package main

import (
	"bytes"
	"compress/gzip"
	"io"
	"strings"
	"testing"
)

// sample has three INSERTs with the aura columns of the three effects. 458 and 6648 apply
// SPELL_AURA_MOUNTED (78) in effect 1 and effect 2.
const sample = "DROP TABLE IF EXISTS `spell_template`;\n" +
	"INSERT INTO `spell_template` (`entry`, `school`, `name`, `nameSubtext`, `effectApplyAuraName1`, `effectApplyAuraName2`, `effectApplyAuraName3`) VALUES\n" +
	"(430, 0, 'Drink', '', 0, 0, 0),\n(77, 0, 'Turtle\\'s Shell', NULL, 0, 0, 0),\n(5, 1, 'Two''Quotes, (and parens);', 'x', 0, 0, 0);\n" +
	"INSERT INTO `spell_template` (`name`, `entry`, `effectApplyAuraName1`, `effectApplyAuraName2`, `effectApplyAuraName3`) VALUES ('Tab\\there', 9, 0, 0, 0), ('', 10, 0, 0, 0);\n" +
	"INSERT INTO `spell_template` (`entry`, `name`, `effectApplyAuraName1`, `effectApplyAuraName2`, `effectApplyAuraName3`) VALUES (458, 'Brown Horse', 78, 0, 0), (6648, 'Chestnut Mare', 0, 78, 0);\n"

func gunzipLines(t *testing.T, gz []byte) []string {
	t.Helper()
	zr, err := gzip.NewReader(bytes.NewReader(gz))
	if err != nil {
		t.Fatal(err)
	}
	b, _ := io.ReadAll(zr)
	return strings.Split(strings.TrimSpace(string(b)), "\n")
}

func TestGenerate(t *testing.T) {
	out, err := Generate([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	lines := gunzipLines(t, out)
	want := []string{"5\tTwo'Quotes, (and parens);", "9\tTab here", "77\tTurtle's Shell", "430\tDrink", "458\tBrown Horse", "6648\tChestnut Mare"}
	if len(lines) != 7 || !strings.HasPrefix(lines[0], "# generated by tools/spellnamegen") || strings.Join(lines[1:], "|") != strings.Join(want, "|") {
		t.Fatalf("%q", lines)
	}
}

func TestGenerateMounts(t *testing.T) {
	out, err := GenerateMounts([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	lines := gunzipLines(t, out)
	if len(lines) != 3 || !strings.HasPrefix(lines[0], "# generated by tools/spellnamegen") || lines[1] != "458" || lines[2] != "6648" {
		t.Fatalf("%q", lines)
	}
}

func TestGenerateRejectsBadInput(t *testing.T) {
	for _, in := range []string{
		"nothing here",
		"INSERT INTO `spell_template` (`entry`, `school`) VALUES (1, 2);",
		"INSERT INTO `spell_template` (`entry`, `name`) VALUES (1, 'a', 3);",
		"INSERT INTO `spell_template` (`entry`, `name`) VALUES (x, 'a');",
		"INSERT INTO `spell_template` (`entry`, `name`) VALUES (1, 'a')",
		"INSERT INTO `spell_template` (`entry`, `name`, `effectApplyAuraName1`) VALUES (1, 'a', 0);",
	} {
		if _, err := Generate([]byte(in)); err == nil {
			t.Errorf("Generate accepted %q", in)
		}
		if _, err := GenerateMounts([]byte(in)); err == nil {
			t.Errorf("GenerateMounts accepted %q", in)
		}
	}
}
